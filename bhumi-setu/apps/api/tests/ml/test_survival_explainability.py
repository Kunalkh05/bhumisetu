# --- INVARIANT 10: DETERMINISTIC EXPLANATIONS ---

def test_top_contributors_deterministic(train_features, explainer):
    """Invariant 10: Repeated explanation calls on same input yield identical top contributors."""
    row = train_features.iloc[10]
    expl_1 = explainer.explain_snapshot(row, prediction_timestamp="2026-09-30T00:00:00Z")
    expl_2 = explainer.explain_snapshot(row, prediction_timestamp="2026-09-30T00:00:00Z")

    assert expl_1.linear_predictor == expl_2.linear_predictor
    assert expl_1.relative_hazard == expl_2.relative_hazard
    assert len(expl_1.top_positive_contributors) == len(expl_2.top_positive_contributors)
    assert len(expl_1.top_negative_contributors) == len(expl_2.top_negative_contributors)
    for c1, c2 in zip(expl_1.top_positive_contributors, expl_2.top_positive_contributors):
        assert c1.feature_name == c2.feature_name
        assert c1.contribution == c2.contribution


# --- INVARIANT 11: ARTIFACT SAVE AND LOAD ---

def test_artifact_save_load_preserves_explanations(tmp_path, train_features, explainer):
    """Invariant 11: Explanation artifacts serialize to JSON and CSV with complete preservation."""
    sample = train_features.iloc[:10]
    expls = explainer.explain_dataframe(sample)
    from explainability.survival_explainability import save_explanation_artifacts
    saved = save_explanation_artifacts(expls, tmp_path)

    assert saved["explanations_json"].exists()
    assert saved["explanations_csv"].exists()

    with open(saved["explanations_json"]) as f:
        loaded_json = json.load(f)
    assert len(loaded_json) == 10
    assert loaded_json[0]["case_id"] == expls[0].case_id
    assert loaded_json[0]["linear_predictor"] == expls[0].linear_predictor


