# --- INVARIANT 18: NO CAUSAL LANGUAGE ---

def test_no_causal_language_in_explanation_engine(train_features, explainer):
    """Invariant 18: Explanations must strictly use associative, non-causal phrasing."""
    banned_words = ["caused", "causation", "responsible for delay", "caused the delay", "caused progress"]
    sample = train_features.iloc[:20]
    for _, row in sample.iterrows():
        expl = explainer.explain_snapshot(row)
        for c in expl.all_contributions:
            narrative_lower = c.explanation_narrative.lower()
            for bw in banned_words:
                assert bw not in narrative_lower, f"Causal violation: found '{bw}' in '{c.explanation_narrative}'"
        off_view = explainer.to_officer_view(expl)
        summary_lower = off_view.summary_narrative.lower()
        for bw in banned_words:
            assert bw not in summary_lower, f"Causal violation in summary: found '{bw}'"
