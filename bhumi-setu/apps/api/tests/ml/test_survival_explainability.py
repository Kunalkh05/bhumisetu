# --- INVARIANT 1: ADDITIVE DECOMPOSITION TO LINEAR PREDICTOR ---

def test_sum_of_feature_contributions_equals_linear_predictor(train_features, explainer):
    """Invariant 1: Sum of beta_j * x_j must exactly equal the linear predictor."""
    sample = train_features.iloc[:30]
    for _, row in sample.iterrows():
        expl = explainer.explain_snapshot(row)
        sum_contribs = sum(c.contribution for c in expl.all_contributions)
        assert abs(sum_contribs - expl.linear_predictor) < 1e-5, (
            f"Sum mismatch: {sum_contribs} != {expl.linear_predictor}"
        )


# --- INVARIANT 2: MULTIPLICATIVE HAZARD MULTIPLIER ---

def test_exp_linear_predictor_equals_relative_hazard(train_features, explainer):
    """Invariant 2: exp(linear_predictor) and prod(hazard_multipliers) must equal relative_hazard."""
    sample = train_features.iloc[:30]
    for _, row in sample.iterrows():
        expl = explainer.explain_snapshot(row)
        expected_hazard = float(np.exp(expl.linear_predictor))
        assert abs(expl.relative_hazard - expected_hazard) < 1e-5, (
            f"Relative hazard mismatch: {expl.relative_hazard} != {expected_hazard}"
        )
        prod_mults = float(np.prod([c.hazard_multiplier for c in expl.all_contributions]))
        assert abs(prod_mults - expl.relative_hazard) < 1e-4, (
            f"Multiplier product mismatch: {prod_mults} != {expl.relative_hazard}"
        )


