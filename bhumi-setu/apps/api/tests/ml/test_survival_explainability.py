# --- INVARIANT 5: POINT-IN-TIME FEATURE FIDELITY ---

def test_explanation_uses_exact_snapshot_features(train_features, explainer):
    """Invariant 5: Feature values in explanation must match input snapshot values exactly."""
    row = train_features.iloc[5]
    expl = explainer.explain_snapshot(row)
    for c in expl.all_contributions:
        if c.feature_name in row and not pd.isna(row[c.feature_name]):
            if isinstance(row[c.feature_name], (int, float)):
                assert abs(float(c.raw_value) - float(row[c.feature_name])) < 1e-5


