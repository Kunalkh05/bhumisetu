# --- INVARIANT 13: TRANSITION ISOLATION ---

def test_transition_isolation(train_features, explainer):
    """Invariant 13: Explanations strictly isolate features by transition."""
    for trans in ["SECTION_11_TO_SECTION_19", "SECTION_19_TO_AWARD", "CASE_INITIATION_TO_MILESTONE"]:
        sub = train_features[train_features["transition"] == trans]
        expl = explainer.explain_snapshot(sub.iloc[0])
        assert expl.transition == trans
